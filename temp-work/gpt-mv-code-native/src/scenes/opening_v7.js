import {renderOpeningV6} from './opening_v6.js';
import {PALETTE as P} from '../engine/palette.js';
import {easeInOut,easeOut,lerp,prog} from '../engine/timing.js';

const BPM=116,OFF=.28,PB=60/BPM;
const B=n=>OFF+n*PB;
const C1=B(6),C2=B(13),C3=B(20),END=15;
const P0={x:850,y:110,w:730,h:805};
const P1={x:-170,y:30,w:1080,h:1000};
const WORLD_DST={x:735,y:65,w:1080,h:995};

function cleanArt(d,model,dst,{crop='bust',clip=null,alpha=1}={}){
  d.save(()=>{
    if(clip){d.g.beginPath();d.g.rect(clip.x,clip.y,clip.w,clip.h);d.g.clip();}
    model.draw(d.g,dst,{crop,alpha});
  });
}

function proofSheet(d,t,start,end,{y=900,reverse=false,accent=P.cobalt}={}){
  const q=prog(t,start,end);if(q<=0||q>=1)return;
  const k=easeInOut(q),x=reverse?lerp(2070,-520,k):lerp(-520,2070,k);
  d.save(()=>{
    d.g.translate(x,y);d.g.rotate(reverse?.10:-.12);
    d.rrect(0,0,430,165,14,{fill:P.white,stroke:P.line,width:1.4,alpha:.96,shadow:.42});
    d.line(36,45,330,45,{color:accent,width:8,alpha:.58});
    d.rrect(36,82,250,7,3,{fill:P.line,alpha:.34});
    d.rrect(36,105,190,7,3,{fill:P.line,alpha:.28});
  });
}

function fixBuildDepth(d,t,model){
  // V5/V6 lay the four context objects across the eyes. Restore only the face/hair
  // after those objects: they now read as material orbiting BEHIND the subject.
  const a=easeOut(prog(t,1.35,2.18));
  if(a>0)cleanArt(d,model,P0,{crop:'bust',alpha:a,clip:{x:930,y:155,w:650,h:505}});
}

function fixContextDepth(d,t,model){
  const push=easeInOut(prog(t,C1,C1+.72));
  const dst={x:lerp(P0.x,P1.x,push),y:lerp(P0.y,P1.y,push),w:lerp(P0.w,P1.w,push),h:lerp(P0.h,P1.h,push)};
  // Keep all four objects visible, but never through her eyes. Restore head/shoulder only.
  cleanArt(d,model,dst,{crop:'bust',clip:{x:0,y:70,w:900,h:650}});
  // One deliberately near-lens proof crosses last, restoring a true foreground plane.
  proofSheet(d,t,C1+.56,C1+1.74,{y:875,accent:P.gold});
}

function fixPromptDepth(d,t,model){
  // The prompt sheet passes BEHIND the character edge instead of sitting on top of her face.
  cleanArt(d,model,P1,{crop:'bust',clip:{x:0,y:0,w:530,h:1080},alpha:.99});
  d.line(522,180,522,900,{color:P.cobalt,width:3,alpha:.13});

  // The rejected false start physically leaves the composition during backspace.
  const q=(t-C2)/PB,del=prog(q,2.22,3.28);
  if(del>0&&del<1){
    const k=easeOut(del);
    for(let i=0;i<4;i++){
      const x=lerp(860+i*82,1850+i*42,k),y=lerp(545+i*11,330+i*92,k);
      d.save(()=>{d.g.translate(x,y);d.g.rotate(-.20+i*.11+k*.18);d.rrect(-68,-6,136,12,5,{fill:P.coral,alpha:.52*(1-k*.45),shadow:.10});});
    }
  }
  const retry=easeOut(prog(q,3.72,5.05));
  if(retry>0)for(let i=0;i<5;i++){
    const a=easeOut(prog(retry,i*.10,.45+i*.10));
    d.circle(650+i*116,705,5,{fill:i%2?P.gold:P.cobalt,alpha:.30*a});
  }
}

function fixWorldDepth(d,t,model){
  // Buildings are construction generated by the answer, not bars pasted over her face.
  // Reprint the same source art cleanly above the architecture, then restore moving
  // proof sheets above her. Background -> world -> subject -> foreground is explicit.
  const move=easeInOut(prog(t,C3,C3+1.28)),pull=easeInOut(prog(t,C3+.20,C3+1.15));
  const dst={x:lerp(P1.x,WORLD_DST.x,move),y:lerp(P1.y,WORLD_DST.y,move),w:lerp(P1.w,WORLD_DST.w,move),h:lerp(P1.h,WORLD_DST.h,move)};
  const crop=model.morphCrop('bust','full',pull);
  const reveal=easeOut(prog(t,C3,C3+.70));
  cleanArt(d,model,dst,{crop,clip:{x:0,y:0,w:lerp(540,1920,reveal),h:940},alpha:.995});
  proofSheet(d,t,C3+.70,END-.20,{y:900,accent:P.cobalt});
  proofSheet(d,t,C3+1.00,END-.05,{y:1010,reverse:true,accent:P.gold});
}

export function renderOpeningV7(d,t,model){
  renderOpeningV6(d,t,model);
  if(t<C1)fixBuildDepth(d,t,model);
  else if(t<C2)fixContextDepth(d,t,model);
  else if(t<C3)fixPromptDepth(d,t,model);
  else fixWorldDepth(d,t,model);
}

export const OPENING_V7_CUTS=[0,C1,C2,C3,END];
