#!/usr/bin/env python3
"""Topologically seeded exact sparse-graph TSP reoptimization.

Begin with a low-cost disconnected 2-factor (generated by exact positive
2-edge exchange(s) across the 51-switch neutral family), locate its small
isolated cycle(s), then grow a candidate edge pool by graph distance from
*all* their cities in the published 248,972-edge graph.

Unlike the face-spin patches, this lets locally costly chords and
arbitrarily many edge exchanges participate. All unchanged baseline tour
paths are contracted, and AddCircuit forces exactly one global cycle.
"""
import argparse, importlib.util, json, os, sys, time
from collections import deque
from pathlib import Path
from ortools.sat.python import cp_model
sys.path.insert(0,str(Path(__file__).resolve().parent))
import contracted_circuit_search as core

def tour_edges(t):return {core.ek(t[i],t[(i+1)%len(t)]) for i in range(len(t))}
def components(n,es):
    adj=[[] for _ in range(n)]
    for a,b in es:adj[a].append(b);adj[b].append(a)
    assert all(len(x)==2 for x in adj)
    seen=bytearray(n)
    cycles=[]
    for start in range(n):
        if seen[start]:continue
        now=start;prev=-1;cycle=[]
        while not seen[now]:
            seen[now]=1;cycle.append(now)
            a,b=adj[now];nxt=a if a!=prev else b
            prev,now=now,nxt
        assert now==start
        cycles.append(cycle)
    return sorted(cycles,key=len)
def make_seed(baseline,moves,motifs,mode):
    tour=[int(x)-1 for x in baseline]
    n=len(tour)
    edges=tour_edges(tour)
    if mode=='single':
        # Independently observed source: exact degree-two control at 2026-10-29
        mask=17179869184
        indices=[52]
    else:
        mask=0
        indices=[52,105]
    choices=moves['selected_indices']
    for i,choice in enumerate(choices):
        if (mask>>i)&1:
            move=moves['moves'][choice]
            for a,b in move['removed']:edges.remove(core.ek(a-1,b-1))
            for a,b in move['added']:edges.add(core.ek(a-1,b-1))
    for j in indices:
        motif=motifs[j]
        for a,b in motif['old']:
            e=core.ek(a-1,b-1);assert e in edges
            edges.remove(e)
        for a,b in motif['added']:
            e=core.ek(a-1,b-1);assert e not in edges
            edges.add(e)
    assert len(edges)==n
    cycles=components(n,edges)
    assert len(cycles)>=2
    assert len(cycles[0])<=20
    return [v for cycle in cycles if len(cycle)<=20 for v in cycle], [len(x) for x in cycles],indices

def main():
    p=argparse.ArgumentParser()
    for arg in ('graph','baseline','neutral-moves','motifs','report','output'):
        p.add_argument('--'+arg,required=True)
    p.add_argument('--mode',choices=['single','double'],default='single')
    p.add_argument('--radius',type=int,default=3)
    p.add_argument('--max-vertices',type=int,default=4000)
    p.add_argument('--include-neutral',action='store_true')
    p.add_argument('--seconds',type=int,default=120)
    p.add_argument('--workers',type=int,default=4)
    p.add_argument('--allow-equal',action='store_true')
    args=p.parse_args()
    start=time.monotonic()
    baseline=json.loads(Path(args.baseline).read_text())['tour']
    n=len(baseline)
    assert n==100000
    tour=[v-1 for v in baseline]
    base=tour_edges(tour)
    W=core.source_graph(args.graph,n)
    assert base<=W.keys()
    moves=json.loads(Path(args.neutral_moves).read_text())
    motifs=json.loads(Path(args.motifs).read_text())['positive_repair_motifs']
    seed,source_components,source_indices=make_seed(baseline,moves,motifs,args.mode)
    graph=[[] for _ in range(n)]
    for u,v in W:
        graph[u].append(v);graph[v].append(u)
    area=set(seed)
    q=deque((v,0) for v in seed)
    oversized=False
    while q and not oversized:
        v,d=q.popleft()
        if d>=args.radius:continue
        for u in graph[v]:
            if u not in area:
                area.add(u)
                if len(area)>args.max_vertices:
                    oversized=True
                    break
                q.append((u,d+1))
    report={'status':'UNSTARTED','seed_mode':args.mode,
            'seed_motif_indices':source_indices,'seed_components':source_components,
            'seed_vertices_1based':[v+1 for v in seed],'radius':args.radius,
            'area_vertices':len(area),'max_vertices':args.max_vertices,
            'include_neutral':args.include_neutral,'time_limit_seconds':args.seconds}
    if oversized:
        report['status']='SKIPPED_TOO_MANY_VERTICES'
    else:
        pool={e for e in W if e not in base and e[0] in area and e[1] in area}
        if args.include_neutral:
            for move in moves['moves']:
                for a,b in move['added']:
                    e=core.ek(a-1,b-1)
                    assert e in W and e not in base
                    pool.add(e)
        assert pool
        active,ordered,macros=core.build_active(tour,base,pool)
        report.update({'nonbase_candidate_edges':len(pool),
               'flexible_vertices':len(ordered),'variable_edges':len(active),
               'fixed_paths':len(macros)})
        spec=importlib.util.spec_from_file_location('p010verify',
           Path(os.environ['FEWSHOTS_ROOT'])/'problems/p010-mona-lisa-tsp/verify/verify.py')
        ver=importlib.util.module_from_spec(spec);spec.loader.exec_module(ver)
        assert ver.tour_length(baseline)==5757191
        xs,ys=ver.coordinates()
        for a,b in pool:
            assert ver.euc_2d(xs[a]-xs[b],ys[a]-ys[b])==W[(a,b)]
        m=cp_model.CpModel()
        index={v:i for i,v in enumerate(ordered)}
        arcs=[];var={};terms=[];oldcost=0
        for a,b in sorted(active):
            x=m.NewBoolVar(f'x{a}_{b}')
            f=m.NewBoolVar(f'F{a}_{b}');r=m.NewBoolVar(f'R{a}_{b}')
            m.Add(f+r==x)
            arcs.extend(((index[a],index[b],f),(index[b],index[a],r)))
            var[(a,b)]=x
            terms.append(W[(a,b)]*x)
            if (a,b) in base:oldcost+=W[(a,b)]
        for a,b in macros:
            f=m.NewBoolVar(f'MF{a}_{b}');r=m.NewBoolVar(f'MR{a}_{b}')
            m.Add(f+r==1)
            arcs.extend(((index[a],index[b],f),(index[b],index[a],r)))
        m.AddCircuit(arcs)
        delta=sum(terms)-oldcost
        m.Add(delta <= (0 if args.allow_equal else -1))
        m.Minimize(delta)
        s=cp_model.CpSolver()
        s.parameters.num_search_workers=args.workers
        s.parameters.max_time_in_seconds=args.seconds
        s.parameters.random_seed=427
        print(json.dumps({'stage':'model',**report}),flush=True)
        result=s.Solve(m)
        report.update({'status':s.StatusName(result),'branches':s.NumBranches(),
                       'conflicts':s.NumConflicts(),'lower_bound':s.BestObjectiveBound()})
        if result in (cp_model.FEASIBLE,cp_model.OPTIMAL):
            selected={e for e,x in var.items() if s.Value(x)}
            candidate=core.reconstruct(tour,base,active,selected)
            score=ver.tour_length(candidate)
            assert score==5757191+sum(W[e] for e in selected)-oldcost
            assert score<5757191 or args.allow_equal and score==5757191
            out=Path(args.output);out.parent.mkdir(parents=True,exist_ok=True)
            out.write_text(json.dumps({'tour':candidate},separators=(',',':')))
            report.update({'verified_score':score,'improvement':5757191-score,
                           'canonical_hash':ver.canonical_hash({'tour':ver.canonical_tour(candidate)})})
    report['wall_seconds']=round(time.monotonic()-start,2)
    dest=Path(args.report);dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'stage':'result',**report}),flush=True)

if __name__=='__main__':main()
