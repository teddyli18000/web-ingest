#!/usr/bin/env python3
"""Strengthened exact W129/W131 feasibility model with order-10 quotient table.

The base XOR model fixes the exact full-sequence structural case.  This wrapper
adds a redundant but strong necessary condition: the ten residue sums of A and B,
together with their six independent order-10 periodic autocorrelation quotient
values, must occur in the exact quotient-profile table generated by
oddperfect_h20_w129_w131_order10_profiles.cpp.

Any FEASIBLE sequence is independently rescored by the base model.  UNKNOWN is
not evidence of exclusion.
"""
from __future__ import annotations
import argparse,json,sys
from ortools.sat.python import cp_model
import oddperfect_h20_w129_w131_xor_cpsat as base

TYPE={
    'W129-A':'low11',
    'W131-A2':'low11',
    'W131-B1':'low11',
    'W131-A0':'a0',
    'W131-B3':'low12',
}
MASK=(1<<26)-1

def decode(code:int):
    out=[]
    for _ in range(10):
        out.append(-5+2*(code%6));code//=6
    return out

def load_rows(path:str):
    rows=[]
    with open(path) as f:
        for line in f:
            z,*rv=map(int,line.split())
            if len(rv)!=6: raise ValueError('bad profile row')
            ca=z&MASK;cb=z>>26
            rows.append(decode(ca)+decode(cb)+rv)
    rows=sorted(set(tuple(r) for r in rows))
    return [list(r) for r in rows]

def build(case:str,profiles:str):
    model,x,corr,targetE=base.build(case)
    sums=[]
    for half in (0,1):
        for r in range(10):
            neg=[x[2*i+half] for i in range(50) if i%10==r]
            s=model.NewIntVar(-5,5,f'ord10_s_{half}_{r}')
            model.Add(s==5-2*sum(neg));sums.append(s)
    # Periodic half-autocorrelation quotient. P_r=C_{2r}+C_{100-2r},
    # P_25=2*C_50, P_0=100.  R_q sums P_r over r=q (mod 10).
    R=[]
    for q in range(6):
        terms=[];const=0
        for r in range(50):
            if r%10!=q: continue
            if r==0: const+=100
            elif r==25: terms.extend([corr[50],corr[50]])
            else: terms.extend([corr[2*r],corr[100-2*r]])
        v=model.NewIntVar(-500,500,f'ord10_R{q}')
        model.Add(v==const+sum(terms));R.append(v)
    rows=load_rows(profiles)
    model.AddAllowedAssignments(sums+R,rows)
    return model,x,corr,targetE,len(rows),sums,R

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--case',required=True,choices=sorted(TYPE));ap.add_argument('--profiles',required=True)
    ap.add_argument('--seconds',type=float,default=240);ap.add_argument('--workers',type=int,default=1);ap.add_argument('--seed',type=int,default=1);args=ap.parse_args()
    model,x,corr,targetE,nrows,sums,R=build(args.case,args.profiles)
    err=model.Validate()
    if err: raise SystemExit('MODEL_INVALID '+err)
    s=cp_model.CpSolver();s.parameters.max_time_in_seconds=args.seconds;s.parameters.num_search_workers=args.workers;s.parameters.random_seed=args.seed;s.parameters.randomize_search=True;s.parameters.cp_model_presolve=True;s.parameters.symmetry_level=2
    st=s.Solve(model)
    out={'case':args.case,'profile_type':TYPE[args.case],'profile_rows':nrows,'target_energy':targetE,'status':s.StatusName(st),'wall_time':s.WallTime(),'branches':s.NumBranches(),'conflicts':s.NumConflicts(),'workers':args.workers}
    if st in (cp_model.FEASIBLE,cp_model.OPTIMAL):
        seq=''.join('-' if s.Value(v) else '+' for v in x);e,odd,cs,a,b=base.exact(seq)
        ok=(e==targetE and odd==50 and a==20 and b==0 and all(abs(cs[k])==1 for k in range(1,100,2)))
        out.update(sequence=seq,energy=e,odd_energy=odd,asum=a,bsum=b,independent_check=ok,residue_sums=[s.Value(v) for v in sums],quotient_R=[s.Value(v) for v in R])
        print(json.dumps(out,sort_keys=True),flush=True);return 0 if ok else 3
    print(json.dumps(out,sort_keys=True),flush=True);return 0 if st==cp_model.INFEASIBLE else 2
if __name__=='__main__':sys.exit(main())
