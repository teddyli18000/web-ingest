// kp=17,kc=2 with support overlap t=2.
//
// Since sum c=0, its two nonzero entries are +1,-1.  Up to AGL(1,Z25)
// and the harmless global sign c->-c, their separation has exactly two
// classes: d=1 (unit difference) and d=5 (difference divisible by 5).
// Normalize c=delta_0-delta_d.
//
// The complete periodic cross equation p c* + c p*=0 is linear in p:
//   p_r-p_(r+d)+p_(-r)-p_(d-r)=0.
// Its rational RREF is integral.  For d=1 it has 13 free ternary variables;
// for d=5 it has 15.  We enumerate all 3^13+3^15 assignments, reconstruct
