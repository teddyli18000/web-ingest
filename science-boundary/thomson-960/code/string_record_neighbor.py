#!/usr/bin/env python3
"""Simplified spherical string / climbing-image search for the R<->A barrier.

Endpoints:
  R = live merged Few Shots p007 record.
  A = durable symmetry-broken +0.003280 neighbor in data/neighbor-soft-003280.json.

A and R retain a pointwise correspondence because A was generated by a smooth
full-space perturbation/relaxation of R.  The path is represented by a small
number of images on (S^2)^960.  Each iteration takes a capped Riemannian
steepest-descent step on every interior image, then reparameterizes the string
to equal RMS-geodesic arc length.  After the string settles, the highest-energy
image is refined with a climbing-image force that reverses the gradient
component along the local path tangent.

This is not used to score a candidate directly.  Its purpose is to locate the
low R<->A saddle geometry so transverse perturbations can search exits not
aligned with the already-known R/A basin edge.
"""
from __future__ import annotations
import argparse, json, math, pathlib, re
import numpy as np

N=960
P007=pathlib.Path('problems/p007-thomson-problem')


def find_live(root):
    best=None
    for md in (root/P007/'shots').glob('*/*/SHOT.md'):
        m=re.search(r'^claimed_score\s*=\s*"([0-9.]+)"',md.read_text(),re.M)
        if m:
            item=(float(m.group(1)),md.parent)
            if best is None or item[0]<best[0]: best=item
    if best is None: raise RuntimeError('no merged p007 shot')
    return best

def cert_xyz(path):
    d=json.loads(path.read_text()); x=np.array([[a/q,b/q,c/q] for a,b,c,q in d['points']],float)
    return x/np.linalg.norm(x,axis=1)[:,None]
def float_xyz(path):
    d=json.loads(path.read_text()); p=d.get('points') if isinstance(d,dict) else d
    x=np.asarray(p,float); return x/np.linalg.norm(x,axis=1)[:,None]

def energy_grad(x):
    dots=np.clip(x@x.T,-1,1); r2=np.maximum(2-2*dots,1e-300); np.fill_diagonal(r2,np.inf)
    inv=1/np.sqrt(r2); E=float(np.sum(np.triu(inv,1),dtype=np.longdouble))
    w=inv/r2; np.fill_diagonal(w,0)
    g=w@x-np.sum(w,axis=1)[:,None]*x
    g-=np.sum(g*x,axis=1)[:,None]*x
    return E,g

def logmap(x,y):
    dot=np.clip(np.sum(x*y,axis=1),-1,1); th=np.arccos(dot)
    w=y-dot[:,None]*x; nw=np.linalg.norm(w,axis=1); v=np.zeros_like(x); m=nw>1e-14
    v[m]=w[m]*(th[m]/nw[m])[:,None]
    return v

def expmap(x,v):
    a=np.linalg.norm(v,axis=1); y=np.empty_like(x); m=a>1e-14
    y[~m]=x[~m]; y[m]=np.cos(a[m,None])*x[m]+np.sin(a[m,None])*v[m]/a[m,None]
    return y/np.linalg.norm(y,axis=1)[:,None]
def slerp(x,y,t):
    return expmap(x,t*logmap(x,y))
def rms_geo(x,y):
    a=np.arccos(np.clip(np.sum(x*y,axis=1),-1,1)); return float(np.sqrt(np.mean(a*a)))
def interpolate_endpoints(A,B,nimages):
    return [slerp(A,B,i/(nimages-1)) for i in range(nimages)]
def reparameterize(images):
    seg=[rms_geo(images[i],images[i+1]) for i in range(len(images)-1)]
    cum=np.concatenate([[0.0],np.cumsum(seg)]); total=float(cum[-1])
    if total<=0: return images,total
    out=[images[0]]
    for k in range(1,len(images)-1):
        target=total*k/(len(images)-1); j=int(np.searchsorted(cum,target,side='right')-1); j=min(j,len(seg)-1)
        f=(target-cum[j])/max(seg[j],1e-15); out.append(slerp(images[j],images[j+1],float(f)))
    out.append(images[-1]); return out,total

def capped_descent(x,g,eta,max_rms):
    v=-eta*g; rms=float(np.sqrt(np.mean(np.sum(v*v,axis=1))))
    if rms>max_rms: v*=max_rms/rms
    return expmap(x,v),min(rms,max_rms)
def path_tangent(images,i):
    # Average forward and reverse-geodesic directions, both represented at image i.
    f=logmap(images[i],images[i+1]); b=-logmap(images[i],images[i-1]); t=f+b
    norm=float(np.sqrt(np.sum(t*t)))
    if norm<1e-14: t=f; norm=float(np.sqrt(np.sum(t*t)))
    return t/max(norm,1e-30)
def climb_step(x,g,tau,eta,max_rms):
    # Descent perpendicular to path; ascent along path.
    dot=float(np.sum(g*tau)); force=-g+2*dot*tau
    v=eta*force; rms=float(np.sqrt(np.mean(np.sum(v*v,axis=1))))
    if rms>max_rms: v*=max_rms/rms
    return expmap(x,v),min(rms,max_rms)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('few_shots'); ap.add_argument('--neighbor-json',required=True)
    ap.add_argument('--images',type=int,default=9); ap.add_argument('--iterations',type=int,default=220)
    ap.add_argument('--eta',type=float,default=2.5e-4); ap.add_argument('--max-step',type=float,default=7e-4)
    ap.add_argument('--climb-iterations',type=int,default=180); ap.add_argument('--out',required=True)
    args=ap.parse_args(); root=pathlib.Path(args.few_shots); live_score,live_dir=find_live(root)
    R=cert_xyz(live_dir/'certificate.json'); A=float_xyz(pathlib.Path(args.neighbor_json)); images=interpolate_endpoints(R,A,args.images)
    hist=[]
    for it in range(args.iterations):
        vals=[]; grads=[]
        for x in images:
            E,g=energy_grad(x); vals.append(E); grads.append(g)
        maxstep=0.0; new=[images[0]]
        for i in range(1,len(images)-1):
            y,s=capped_descent(images[i],grads[i],args.eta,args.max_step); new.append(y); maxstep=max(maxstep,s)
        new.append(images[-1]); images,total=reparameterize(new)
        if it%10==0 or it==args.iterations-1:
            imax=int(np.argmax(vals)); barrier=max(vals)-min(vals[0],vals[-1]); print(f'iter={it} maxE={max(vals):.12f} imax={imax} barrier={barrier:.9g} arc={total:.6g} step={maxstep:.3e}',flush=True)
            hist.append({'iteration':it,'energies':vals,'max_index':imax,'arc':total,'max_step':maxstep})
    vals=[energy_grad(x)[0] for x in images]; imax=int(np.argmax(vals)); saddle=images[imax].copy()
    if imax in (0,len(images)-1): raise RuntimeError('maximum collapsed to endpoint')
    # Keep neighboring images fixed during a bounded climbing refinement.
    left=images[imax-1]; right=images[imax+1]; climb=[]
    for it in range(args.climb_iterations):
        E,g=energy_grad(saddle); tmp=images.copy(); tmp[imax]=saddle; tau=path_tangent(tmp,imax)
        saddle,s=climb_step(saddle,g,tau,args.eta,args.max_step*0.7)
        grms=float(np.sqrt(np.mean(np.sum(g*g,axis=1))))
        if it%10==0 or it==args.climb_iterations-1:
            print(f'climb={it} E={E:.12f} grad_rms={grms:.6g} step={s:.3e}',flush=True)
            climb.append({'iteration':it,'energy':E,'grad_rms':grms,'step':s})
    Es,gs=energy_grad(saddle); grms=float(np.sqrt(np.mean(np.sum(gs*gs,axis=1))))
    out={'live_score':live_score,'live_shot':str(live_dir.relative_to(root)),'images':args.images,'iterations':args.iterations,
         'endpoint_record_energy':energy_grad(R)[0],'endpoint_neighbor_energy':energy_grad(A)[0],
         'path_energies':[energy_grad(x)[0] for x in images],'max_image_index':imax,'history':hist,
         'climbing_energy':Es,'climbing_gradient_rms':grms,'climb_history':climb,
         'saddle_points':saddle.tolist()}
    pathlib.Path(args.out).write_text(json.dumps(out,separators=(',',':'))+'\n')

if __name__=='__main__': main()
