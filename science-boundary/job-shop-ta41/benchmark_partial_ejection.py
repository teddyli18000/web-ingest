#!/usr/bin/env python3
"""Reproducible hidden-answer positive test of partial-order ejection chains.

Original complete starts are independently generated by 20-second native
published N7 and are not derived from the oracle schedules. Search sees
only these 51-line 30x20 start.txt inputs. For each method and seed, use
identical full DAG evaluation budgets; do not give source oracles to C++.
"""
import argparse,json,subprocess,tempfile,time,statistics
from pathlib import Path
from benchmark_hidden_positive import load_start
from search import evaluate

ROOT=Path(__file__).resolve().parent

def main(a):
    paths=sorted(a.cases.glob('ta*js-n7elite*/start.txt'))
    assert len(paths)==12,len(paths)
    if a.cases_filter:
        paths=[p for p in paths if p.parent.name in a.cases_filter]
    a.out.mkdir(parents=True,exist_ok=True)
    trials=[]
    started=time.monotonic()
    with tempfile.TemporaryDirectory() as temp:
        binary=Path(temp)/'partial_chain'
        subprocess.run(['g++','-O3','-std=c++17',
                        str(ROOT/'partial_ejection_chain.cpp'),
                        '-o',str(binary)],check=True)
        for path in paths:
            pos,dur,incumbent=load_start(path)
            for seed in a.seeds:
                cert=Path(temp)/'out.txt'
                tick=time.monotonic()
                result=subprocess.run([str(binary),str(path),str(cert),
                         a.policy,str(seed),str(a.evaluations),
                         str(a.max_pool),str(a.restart_evals)],
                         capture_output=True,text=True,timeout=a.timeout,check=False)
                if result.returncode:
                    raise RuntimeError(f'{path.parent.name} seed={seed}: exit={result.returncode}; stderr={result.stderr[-1000:]}')
                lines=cert.read_text().splitlines()
                stat=lines[0].split()
                assert len(stat)==11,(path.parent.name,stat)
                best,used,accepted,ejections,complete,restarts,maxpool,novel,initialpool,secs,found=stat
                best=int(best);used=int(used)
                orders=[list(map(int,line.split())) for line in lines[1:]]
                assert len(orders)==20 and all(sorted(row)==list(range(30)) for row in orders)
                verified=evaluate(orders,pos,dur)
                assert verified==best and best<=incumbent,(path.parent.name,verified,best,incumbent)
                record=dict(case=path.parent.name,seed=seed,policy=a.policy,
                    initial=incumbent,best=best,delta=incumbent-best,
                    exact_DAG_candidate_evaluations=used,
                    budget=a.evaluations,
                    accepted_moves=int(accepted),ejections=int(ejections),
                    full_completions=int(complete),restarts=int(restarts),
                    max_unscheduled_operations=int(maxpool),
                    newly_critical_ejection_moves=int(novel),
                    initial_unscheduled_operations=int(initialpool),
                    native_search_seconds=float(secs),
                    independently_verified_best=verified,
                    hidden_oracle_never_read=True)
                trials.append(record)
                if best<incumbent:
                    (a.out/f'{path.parent.name}-seed{seed}-certificate.json').write_text(
                        json.dumps({'machines':orders},separators=(',',':'))+'\n')
                (a.out/'partial-results.json').write_text(json.dumps(
                    dict(complete=False,trials=trials),indent=2)+'\n')
                print('CASE',path.parent.name,a.policy,'seed',seed,
                      'score',incumbent,'to',best,'evaluations',used,
                      'ejections',int(ejections),flush=True)
    report=dict(policy=a.policy,
        proven_source="Qiming01/Job-Shop-Scheduling@7e120ebada21cb604c871e0657814bf6e32611f8",
        independent_initial_family='20-second source-faithful N7 local optima',
        method='partial schedule with unscheduled pool and alternating insertion/critical-path ejection',
        note='Inspired by original 2018 IEBO; not an exact implementation of IEBO.',
        evaluated_instances=len(paths),
        trial_count=len(trials),
        evaluations_per_trial=a.evaluations,
        successful_improvements=sum(x['delta']>0 for x in trials),
        mean_gain=statistics.mean(x['delta'] for x in trials),
        native_search_seconds_total=sum(x['native_search_seconds'] for x in trials),
        complete=True,trials=trials,
        elapsed_seconds=round(time.monotonic()-started,3))
    (a.out/'results.json').write_text(json.dumps(report,indent=2)+'\n')
    print('RESULT',json.dumps({k:v for k,v in report.items()
          if k!='trials'}),flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--cases',type=Path,default=ROOT/'positive-n7-elite-data')
    p.add_argument('--policy',choices=('dynamic','static','random'),required=True)
    p.add_argument('--cases-filter',nargs='*',default=[])
    p.add_argument('--seeds',nargs='+',type=int,default=[4107,4113])
    p.add_argument('--evaluations',type=int,default=180000)
    p.add_argument('--max-pool',type=int,default=8)
    p.add_argument('--restart-evals',type=int,default=20000)
    p.add_argument('--timeout',type=int,default=120)
    p.add_argument('--out',type=Path,required=True)
    main(p.parse_args())
