#!/usr/bin/env python3
"""Enumerate every exact 3-for-3 exchange of a 367-point C7^5 fiber.

A replacement vertex is legal after removing owner set R iff its conflict
support against the original 367-set is a nonempty subset of R.  For |R|=3,
every owner triple that can be the exact union of three replacement supports is
therefore generated by one of: a size-3 support; size-2+size-1; two size-2
supports; or three size-1 supports.  We then enumerate all pairwise compatible
replacement triples with support union exactly R and test the Hall deficiency
used by the X_294 closure construction.
"""

import argparse
import json
from itertools import combinations
from pathlib import Path

import generalized9 as g
import neutral2_maxsat as nm
import rank3_square_relax as rs
import rank3_x294_two_swap_matching as tw

SPECIAL = 294
BASELINE = 134753


def bits(mask: int):
    while mask:
        lsb = mask & -mask
        yield lsb.bit_length() - 1
        mask ^= lsb


def support_groups(F, digits):
    supports, _ = g.support_masks(F, digits)
    fset = set(F)
    groups = {}
    for v, sm in enumerate(supports):
        if v in fset:
            continue
        bc = sm.bit_count()
        if 1 <= bc <= 3:
            groups.setdefault(sm, []).append(v)
    return supports, groups


def owner_triples(groups):
    singles = sorted(m for m in groups if m.bit_count() == 1)
    doubles = sorted(m for m in groups if m.bit_count() == 2)
    triples = {m for m in groups if m.bit_count() == 3}

    for d in doubles:
        for s in singles:
            u = d | s
            if u.bit_count() == 3:
                triples.add(u)
    for i, a in enumerate(doubles):
        for b in doubles[i + 1 :]:
            u = a | b
            if u.bit_count() == 3:
                triples.add(u)
    for a, b, c in combinations(singles, 3):
        triples.add(a | b | c)
    return sorted(triples), len(singles), len(doubles)


def pool_for(R, groups):
    own = list(bits(R))
    pool = []
    for k in (1, 2, 3):
        for ss in combinations(own, k):
            m = 0
            for i in ss:
                m |= 1 << i
            pool.extend(groups.get(m, ()))
    return sorted(set(pool))


def independent(a, b, c, digits):
    return not g.conflict(a, b, digits) and not g.conflict(a, c, digits) and not g.conflict(b, c, digits)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("r367", type=Path)
    ap.add_argument("baseline", type=Path)
    ap.add_argument("output", type=Path)
    ap.add_argument("status", type=Path)
    ap.add_argument("--family", choices=("r0", "rank3", "x"), required=True)
    args = ap.parse_args()

    digits = tuple(g.dec5(v) for v in range(g.U))
    r0 = g.load_r(args.r367)
    xset = g.make_x(r0, digits)
    r = rs.load_rank3_state(r0, digits)
    rsup, _ = g.support_masks(r, digits)

    base_model, bst = nm.solve_maxsat(rs.RANK3_K9, r, xset, digits, rsup)
    if base_model is None or bst["score"] != BASELINE:
        raise RuntimeError(f"base drift {bst}")
    _, hs, vs = base_model
    x0 = xset[SPECIAL]
    weights = [sum(1 for f in arr if g.conflict(x0, f, digits)) for arr in vs]
    positive = [j for j, c in enumerate(weights) if c]
    if len(positive) != 366 or any(weights[j] != 1 for j in positive):
        raise RuntimeError("weight drift")

    ridx = {j: k for k, j in enumerate(positive)}
    adj_all = [[] for _ in range(g.U)]
    for j in positive:
        k = ridx[j]
        for v in rs.neighborhood(xset[j], digits):
            adj_all[v].append(k)

    F = list(r0 if args.family == "r0" else r if args.family == "rank3" else xset)
    fsup, groups = support_groups(F, digits)
    triples, n_single_groups, n_double_groups = owner_triples(groups)
    n_triple_groups = sum(m.bit_count() == 3 for m in groups)

    base_m = tw.hk([adj_all[v] for v in F], 366)
    if base_m != 366:
        raise RuntimeError(f"base matching {base_m}")

    best_m = base_m
    best = []
    hist = {}
    legal = 0
    candidate_combinations = 0
    max_pool = 0
    owner_triples_with_states = 0

    for R in triples:
        owners = tuple(bits(R))
        if len(owners) != 3:
            raise RuntimeError("bad owner triple")
        pool = pool_for(R, groups)
        max_pool = max(max_pool, len(pool))
        before = legal
        for ia in range(len(pool)):
            a = pool[ia]
            sa = fsup[a]
            for ib in range(ia + 1, len(pool)):
                b = pool[ib]
                if g.conflict(a, b, digits):
                    continue
                sb = fsup[b]
                for ic in range(ib + 1, len(pool)):
                    c = pool[ic]
                    candidate_combinations += 1
                    sc = fsup[c]
                    if (sa | sb | sc) != R:
                        continue
                    if g.conflict(a, c, digits) or g.conflict(b, c, digits):
                        continue
                    G = F.copy()
                    G[owners[0]] = a
                    G[owners[1]] = b
                    G[owners[2]] = c
                    if len(set(G)) != len(G):
                        raise RuntimeError("duplicate replacement state")
                    legal += 1
                    m = tw.hk([adj_all[z] for z in G], 366)
                    hist[m] = hist.get(m, 0) + 1
                    rec = (owners, (a, b, c), G)
                    if m < best_m:
                        best_m = m
                        best = [rec]
                    elif m == best_m and len(best) < 100:
                        best.append(rec)
        if legal > before:
            owner_triples_with_states += 1

    status = {
        "candidate": False,
        "family": args.family,
        "method": "rank3-x294-exact-three-swap-hall",
        "base_matching": base_m,
        "support_groups_1": n_single_groups,
        "support_groups_2": n_double_groups,
        "support_groups_3": n_triple_groups,
        "owner_triples": len(triples),
        "owner_triples_with_states": owner_triples_with_states,
        "max_pool": max_pool,
        "candidate_combinations": candidate_combinations,
        "legal_three_swap_states": legal,
        "matching_histogram": {str(k): v for k, v in sorted(hist.items())},
        "min_matching": best_m,
        "max_closure_objective": 367 - best_m,
        "best_states": [
            {"remove": list(o), "add": list(a)} for o, a, _ in best
        ],
        "base_maxsat": bst,
    }

    if best_m <= 365:
        owners, add, G = best[0]
        bidx = [i for i in range(367) if i not in set(rs.RANK3_K9)]
        baseids = {int(p, 7) for p in json.loads(args.baseline.read_text())["points"]}
        obj, cert, nsel, pen, cost, rm, ad = tw.closure(
            G, weights, xset, digits, hs, vs, r, bidx, baseids
        )
        score = BASELINE + (obj - len(hs[SPECIAL]))
        if len(cert) != score or score <= BASELINE:
            raise RuntimeError(f"closure replay score={score} cert={len(cert)} obj={obj}")
        status.update({
            "candidate": True,
            "score": score,
            "winning_remove": list(owners),
            "winning_add": list(add),
            "closure_objective": obj,
            "selected_endpoints": nsel,
            "penalty_old_v_ports": pen,
            "rc2_cost": cost,
            "removed_vs_baseline": rm,
            "added_vs_baseline": ad,
        })
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(
            json.dumps({"points": [g.dec10(z) for z in sorted(cert)]}, separators=(",", ":")) + "\n"
        )

    args.status.parent.mkdir(parents=True, exist_ok=True)
    args.status.write_text(json.dumps(status, indent=2, sort_keys=True) + "\n")
    print(("FOUND" if status["candidate"] else "NONE"), json.dumps(status, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
