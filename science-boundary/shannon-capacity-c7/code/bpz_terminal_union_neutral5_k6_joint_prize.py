#!/usr/bin/env python3
"""Exact joint terminal-union + neutral5/k6 core-release optimization.

This is the common exact supermodel of two currently separate searches:

1. the full 18-terminal periphery union P=(X x Q) union (Q x X), whose exact
   independence number is 5872 when the full BB core is retained; and
2. the global support universe U generated by the 30 outside-only neutral k=5
   owner sets together with all 32 exact k=6 clique-cover-gap owner sets.

The selected noncore universe is

    V = P union ((U x U) minus BB).

No terminal code, rectangle, maximum witness, or fixed support-factor pair is
chosen in advance.  Selecting v=(x,y) forces exactly the core cells in
(N[x] intersect B) x (N[y] intersect B) to be deleted.  All conflicts inside V
are hard.  The exact objective is

    selected_noncore - deleted_core.

The public record has BB size 128881 and noncore objective 5872; an optimum of
5873 therefore gives a 134754-point certificate.  This finite universe strictly
contains both the fixed-terminal neutral5+k6 global union and the previous
terminal-union all-k6 joint model.
"""
from __future__ import annotations

import argparse
import itertools
import json
from collections import defaultdict
from pathlib import Path

from pysat.formula import WCNF
from pysat.examples.rc2 import RC2

from bpz_global_k6_gap_union_prize import owner_sets as k6_owner_sets
from bpz_joint_row_defects_maxsat import load_geometry

PINNED_COMMIT = "c753408492dde92a239708986d16c15dbf6c3235"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tan_root", type=Path)
    ap.add_argument("neutral_audit", type=Path)
    ap.add_argument("k6_json", type=Path)
    ap.add_argument("output", type=Path)
    ap.add_argument("certificate", type=Path)
    args = ap.parse_args()

    _base, ring, B, fam = load_geometry(args.tan_root.resolve())
    B = set(B)
    audit = json.loads(args.neutral_audit.read_text())
    C5 = [frozenset(map(int, r["owners"])) for r in audit.get("rows", [])
          if int(r["min_owner_intersection"]) == 0]
    if len(C5) != 30:
        raise RuntimeError(("expected 30 outside-neutral k5 supports", len(C5)))
    C6 = k6_owner_sets(args.k6_json.resolve())
    if len(C6) != 32:
        raise RuntimeError(("expected 32 k6 gap supports", len(C6)))
    Cs = list(dict.fromkeys(C5 + C6))

    # Complete factor pool of every selected support family.  Empty support Q
    # is intentionally added separately via the exact terminal union P below.
    U = {z for z in range(ring.n)
         if any((ring.NB[z] & B) <= C and (ring.NB[z] & B) for C in Cs)}
    X = set(fam["N"]) | set(fam["A"]) | set(fam["D"])
    Q = set(fam["H"]) | set(fam["V"])
    if len(X) != 367 or len(Q) != 16:
        raise RuntimeError(("XQ", len(X), len(Q)))
    P = {(x, q) for x in X for q in Q} | {(q, x) for q in Q for x in X}
    if len(P) != 11744:
        # P is a union of two 5872 rectangles before conflict optimization; the
        # two sides are disjoint in the pinned profile.
        raise RuntimeError(("terminal union cardinality", len(P)))

    core = {(x, y) for x in B for y in B}
    support_products = {(x, y) for x in U for y in U if (x, y) not in core}
    V = sorted(P | support_products)
    idx = {p: i for i, p in enumerate(V)}
    n = len(V)

    factors = {x for p in V for x in p}
    supp = {x: tuple(sorted(ring.NB[x] & B)) for x in factors}
    losses = []
    touched = set()
    for x, y in V:
        L = {(a, b) for a in supp[x] for b in supp[y]}
        losses.append(L)
        touched.update(L)
    touched = sorted(touched)
    bidx = {p: i for i, p in enumerate(touched)}

    w = WCNF()
    implications = 0
    for i, L in enumerate(losses):
        for p in L:
            w.append([-(i + 1), n + bidx[p] + 1])
            implications += 1

    first = {x for x, _ in V}
    second = {y for _, y in V}
    nf = {x: ring.NB[x] & first for x in first}
    ns = {y: ring.NB[y] & second for y in second}
    conflicts = 0
    for i, (x, y) in enumerate(V):
        for a in nf[x]:
            for b in ns[y]:
                j = idx.get((a, b))
                if j is not None and j > i:
                    w.append([-(i + 1), -(j + 1)])
                    conflicts += 1

    for i in range(n):
        w.append([i + 1], weight=1)
    for j in range(len(touched)):
        w.append([-(n + j + 1)], weight=1)

    with RC2(w, solver="g4", adapt=True, exhaust=True, incr=True, verbose=0) as rc2:
        model = rc2.compute()
        cost = rc2.cost
    if model is None:
        raise RuntimeError("joint RC2 returned no model")
    pos = {z for z in model if z > 0}
    sel_idx = [i for i in range(n) if i + 1 in pos]
    selected = [V[i] for i in sel_idx]
    deleted = {touched[j] for j in range(len(touched)) if n + j + 1 in pos}
    forced = set()
    for i in sel_idx:
        forced.update(losses[i])
    if deleted != forced:
        raise RuntimeError(("core-deletion drift", len(deleted), len(forced)))
    objective = len(selected) - len(deleted)
    if objective != n - cost:
        raise RuntimeError(("objective drift", objective, n - cost))

    # Independent replay of the exact model.
    for i, p in enumerate(selected):
        nx, ny = ring.NB[p[0]], ring.NB[p[1]]
        for z in selected[i + 1:]:
            if z[0] in nx and z[1] in ny:
                raise RuntimeError(("new-new conflict", p, z))
    retained_core = core - deleted
    for p in selected:
        nx, ny = ring.NB[p[0]], ring.NB[p[1]]
        for z in retained_core:
            if z[0] in nx and z[1] in ny:
                raise RuntimeError(("new-core conflict", p, z))

    score = len(retained_core) + len(selected)
    if score != 128881 + objective:
        raise RuntimeError(("score arithmetic", score, objective))
    candidate = objective >= 5873
    if candidate:
        cand = retained_core | set(selected)
        def enc(p):
            return "".join(str(d) for d in (ring.decode(p[0]) + ring.decode(p[1])))
        args.certificate.parent.mkdir(parents=True, exist_ok=True)
        args.certificate.write_text(
            json.dumps({"points": sorted(enc(p) for p in cand)}, separators=(",", ":")) + "\n"
        )

    out = {
        "method": "exact-joint-terminal-union-neutral5-k6-prize",
        "source_commit": PINNED_COMMIT,
        "neutral5_owner_sets": len(C5),
        "k6_owner_sets": len(C6),
        "distinct_owner_sets": len(Cs),
        "support_union_factor": len(U),
        "terminal_union": len(P),
        "noncore_candidates": n,
        "touched_core": len(touched),
        "implications": implications,
        "conflict_clauses": conflicts,
        "selected_noncore": len(selected),
        "deleted_core": len(deleted),
        "objective": objective,
        "record_noncore_target": 5872,
        "score": score,
        "candidate_materialized": candidate,
        "candidate_score": score if candidate else None,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    print(json.dumps(out, sort_keys=True))


if __name__ == "__main__":
    main()
