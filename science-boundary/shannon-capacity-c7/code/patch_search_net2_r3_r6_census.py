#!/usr/bin/env python3
"""Patch search_net2_r3.cpp into an exact saturated-three-owner census.

The resulting program reuses the exact full-space support recovery and complete
three-owner generator from the radius-3 solver, but counts every independent
4-set in each generated P(U) rather than looking for an independent 5-set.

Completeness for the intended r6 disconnected application additionally uses
the separately replayed r4 precondition alpha(P(W)) <= 2 for every two-owner
set W. Under that condition any three-owner pool with alpha >= 4 must have a
connected selected support hypergraph, hence is generated by either a direct
coverage-3 support or two distinct crossing coverage-2 supports. The original
r3 C/D generators are left enabled as harmless supersets.
"""
import sys
from pathlib import Path

if len(sys.argv) != 3:
    raise SystemExit('usage: patch_search_net2_r3_r6_census.py INPUT OUTPUT')
src = Path(sys.argv[1]).read_text()

needle = "bool has_ind2(const std::vector<std::uint32_t>&p){for(std::size_t i=0;i<p.size();++i)for(std::size_t j=i+1;j<p.size();++j)if(!conflict(p[i],p[j]))return true;return false;}\n}"
insert = r'''bool has_ind2(const std::vector<std::uint32_t>&p){for(std::size_t i=0;i<p.size();++i)for(std::size_t j=i+1;j<p.size();++j)if(!conflict(p[i],p[j]))return true;return false;}
std::uint64_t count_ind4(std::vector<std::uint32_t> p){
 std::sort(p.begin(),p.end());p.erase(std::unique(p.begin(),p.end()),p.end());
 std::uint64_t n=0;
 for(std::size_t i=0;i<p.size();++i)for(std::size_t j=i+1;j<p.size();++j){if(conflict(p[i],p[j]))continue;
  for(std::size_t k=j+1;k<p.size();++k){if(conflict(p[i],p[k])||conflict(p[j],p[k]))continue;
   for(std::size_t l=k+1;l<p.size();++l)if(!conflict(p[i],p[l])&&!conflict(p[j],p[l])&&!conflict(p[k],p[l]))++n;
  }
 }
 return n;
}
}'''
if src.count(needle) != 1:
    raise SystemExit('helper anchor drift')
src = src.replace(needle, insert, 1)

old = "std::unordered_set<std::uint64_t>done3;done3.reserve(g3.size()*2+4000000);std::uint64_t triples_checked=0,eligible=0;std::size_t maxpool=0;"
new = "std::unordered_set<std::uint64_t>done3;done3.reserve(g3.size()*2+4000000);std::uint64_t triples_checked=0,eligible=0,productive4=0,independent4_total=0;std::size_t maxpool=0,max_independent4_per_triple=0;"
if src.count(old) != 1:
    raise SystemExit('counter anchor drift')
src = src.replace(old, new, 1)

start = src.index(" auto check3=[&](std::uint32_t a,std::uint32_t b,std::uint32_t c)->bool{")
end = src.index("\n // Case A:", start)
old_check = src[start:end]
new_check = r''' auto check3=[&](std::uint32_t a,std::uint32_t b,std::uint32_t c)->bool{
  if(a==b||a==c||b==c)return false;
  auto k=key3(a,b,c);if(!done3.insert(k).second)return false;
  auto x=unkey3(k);auto p=pool3(x[0],x[1],x[2]);++triples_checked;maxpool=std::max(maxpool,p.size());
  if(p.size()<4)return false;++eligible;
  auto n4=count_ind4(p);if(n4){++productive4;independent4_total+=n4;max_independent4_per_triple=std::max<std::size_t>(max_independent4_per_triple,n4);}
  return false;
 };'''
src = src[:start] + new_check + src[end:]

marker = ' std::cout<<"{\\"kind\\":\\"none\\",\\"method\\":\\"exact-unrestricted-r3-net2\\"'
pos = src.find(marker)
if pos < 0:
    raise SystemExit('final output anchor drift')
report = r''' std::cout<<"{\"kind\":\"census\",\"method\":\"exact-r6-disconnected-saturated-triple-census\",\"baseline_size\":"<<base.size()<<",\"coverage0\":0,\"coverage1\":";
 std::uint64_t rn1=0;for(auto&g:g1)rn1+=g.size();std::uint64_t rn2=0;for(auto&kv:g2)rn2+=kv.second.size();std::uint64_t rn3=0;for(auto&kv:g3)rn3+=kv.second.size();
 std::cout<<rn1<<",\"coverage2\":"<<rn2<<",\"coverage3\":"<<rn3<<",\"coverage2_groups\":"<<g2.size()<<",\"coverage3_groups\":"<<g3.size()<<",\"active_c1_owners\":"<<active.size()<<",\"heavy_c1_owners\":"<<heavy.size()<<",\"triples_checked\":"<<triples_checked<<",\"eligible_triples_ge4raw\":"<<eligible<<",\"productive_alpha4_triples\":"<<productive4<<",\"independent_quadruples_total\":"<<independent4_total<<",\"max_independent_quadruples_per_triple\":"<<max_independent4_per_triple<<",\"max_supported_pool\":"<<maxpool<<"}\n";
 return 0;
'''
src = src[:pos] + report + src[pos:]
Path(sys.argv[2]).write_text(src)
print('patched exact saturated-triple census')
