#!/usr/bin/env python3
"""Close the BPZ auxiliary 367-set under exact one- and two-point swaps.

All same-side-valid t=9 obstruction masks from the complete 243-state private-
swap component of the main set I are frozen first.  Starting with the complete
243-state one-swap component of the published X, every state is expanded by all
valid simultaneous 2-for-2 replacements whose added vertices have conflict
support of size at most two against that state.  Newly reached states are also
expanded by their one-point private swaps and 2-for-2 swaps.  Search stops only
at closure, a verified t=9 hit, or the explicit state cap.

Thus an untruncated negative run proves absence over the whole X component under
the move system generated by exact 1-for-1 and simultaneous 2-for-2 exchanges.
"""

import argparse,json,sys
from collections import deque
from itertools import combinations,product
from pathlib import Path

Q=7;D=5;U=Q**D;N=367;T=9;TARGET=N*N+T*T


def conflict(a,b,d):return all((x-y)%Q in (0,1,Q-1) for x,y in zip(d[a],d[b]))
def independent(v,d):
    a=list(v);return all(not conflict(x,y,d) for x,y in combinations(a,2))
def values(bits):
    while bits:
        z=bits&-bits;yield z.bit_length()-1;bits^=z

def support_groups(bits,nbmask):
    singles={};doubles={};zeros=[]
    for q in range(U):
        if (bits>>q)&1:continue
        h=nbmask[q]&bits;bc=h.bit_count()
        if bc==0:zeros.append(q)
        elif bc==1:
            a=h.bit_length()-1;singles.setdefault(a,[]).append(q)
        elif bc==2:
            z=list(values(h));key=(z[0],z[1]) if z[0]<z[1] else (z[1],z[0]);doubles.setdefault(key,[]).append(q)
    return singles,doubles,zeros

def private_component(start,nbmask):
    seen={start};front=[start];priv={}
    while front:
        nxt=[]
        for bits in front:
            singles,_,zeros=support_groups(bits,nbmask)
            if zeros:raise RuntimeError('direct-add state encountered in private component')
            pp=sorted((a,q) for a,arr in singles.items() for q in arr);priv[bits]=pp
            for a,q in pp:
                b=bits^(1<<a)^(1<<q)
                if b not in seen:seen.add(b);nxt.append(b)
        front=nxt
    return seen,priv

def obstruction_witnesses(Istart,nbmask,ring,digits):
    Icomp,Ipriv=private_component(Istart,nbmask)
    if len(Icomp)!=243:raise RuntimeError(f'I component drift {len(Icomp)}')
    obs={};eligible=subsets=orientations=sameside=0
    for Ibits in Icomp:
        pp=Ipriv[Ibits]
        if len({a for a,q in pp})<T:continue
        eligible+=1
        for pairs in combinations(pp,T):
            if len({a for a,q in pairs})<T:continue
            subsets+=1
            for o in product((0,1),repeat=T):
                orientations+=1;PH=[q if s else a for (a,q),s in zip(pairs,o)];PV=[a if s else q for (a,q),s in zip(pairs,o)]
                if not independent(PH,digits) or not independent(PV,digits):continue
                sameside+=1;Dset=ring.nbhd(set(PH))&ring.nbhd(set(PV));mask=sum(1<<z for z in Dset)
                obs.setdefault(mask,(Ibits,pairs,o,PH,PV))
    if sameside!=640:raise RuntimeError(f'obstruction count drift {sameside}')
    return obs,{'I_component_states':len(Icomp),'eligible_I_states':eligible,'nine_pair_subsets':subsets,'orientations':orientations,'same_side_valid':sameside,'unique_obstruction_masks':len(obs)}

def build(Ibits,Xbits,pairs,PH,PV,ring):
    I=set(values(Ibits));X=set(values(Xbits));R={a for a,q in pairs};B=I-R;NH=ring.nbhd(set(PH));NV=ring.nbhd(set(PV))
    if X&NH&NV:raise RuntimeError('winner still double-hits')
    X0=X-(NH|NV);XH=X&NH;XV=X&NV;P=set()
    for A,C in ((B,B),(R,X0),(set(PH),XH),(set(PV),XV),(X0,R),(XH,set(PV)),(XV,set(PH))):
        for a in A:
            for c in C:P.add((a,c))
    if len(P)!=TARGET:raise RuntimeError(f'score drift {len(P)}')
    pts=sorted(''.join(map(str,ring.decode(a)+ring.decode(b))) for a,b in P)
    return pts,(len(X0),len(XH),len(XV))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('tan_root',type=Path);ap.add_argument('output',type=Path);ap.add_argument('status',type=Path);ap.add_argument('--cap',type=int,default=100000);args=ap.parse_args()
    root=args.tan_root.resolve();sys.path.insert(0,str(root));from shannon.certificates import Ring
    raw=json.loads((root/'data'/'base_c7.json').read_text());I0=set(map(int,raw['I0']));X0=set(map(int,raw['X']));ring=Ring(D);digits=tuple(ring.decode(v) for v in range(U));nbmask=[sum(1<<z for z in ring.NB[v]) for v in range(U)]
    if len(I0)!=N or len(X0)!=N or not independent(I0,digits) or not independent(X0,digits):raise RuntimeError('base drift')
    Istart=sum(1<<z for z in I0);Xstart=sum(1<<z for z in X0);obs,ost=obstruction_witnesses(Istart,nbmask,ring,digits)
    Xcomp,_=private_component(Xstart,nbmask)
    if len(Xcomp)!=243:raise RuntimeError(f'X private component drift {len(Xcomp)}')
    seen=set(Xcomp);q=deque(Xcomp);parent={b:None for b in Xcomp};processed=0;two_moves=0;one_new=0;two_new=0;truncated=False;winner=None;best_bad=None;best_state=None;zero_states=0;max_single_owners=0;max_double_groups=0
    while q and winner is None:
        bits=q.popleft();processed+=1
        # Exact obstruction check.
        for dm,w in obs.items():
            bad=(bits&dm).bit_count()
            if best_bad is None or bad<best_bad:best_bad=bad;best_state=bits
            if bad==0:winner=(bits,w);break
        if winner:break
        singles,doubles,zeros=support_groups(bits,nbmask);zero_states+=bool(zeros);max_single_owners=max(max_single_owners,len(singles));max_double_groups=max(max_double_groups,len(doubles))
        if zeros:
            # A zero-neighbour vertex would produce a 368-set in C7^5; retain
            # the state in diagnostics rather than silently ignoring it.
            print('ZERO_CONFLICT',len(zeros),flush=True)
        # One-swap moves (needed after a two-swap bridge leaves the original component).
        for a,arr in singles.items():
            for x in arr:
                nb=bits^(1<<a)^(1<<x)
                if nb in seen:continue
                if len(seen)>=args.cap:truncated=True;continue
                seen.add(nb);parent[nb]=(bits,'one',(a,x));q.append(nb);one_new+=1
        # Every relevant owner pair has candidates single[a] U single[b] U double[a,b].
        keys=set(doubles)
        so=sorted(singles)
        keys.update(combinations(so,2))
        # If one owner has >=2 private candidates, arbitrary second removals
        # could matter; a compatible pair here would actually expose a 368-set.
        for a,arr in singles.items():
            if len(arr)>=2:
                for b in values(bits):
                    if b!=a:keys.add((a,b) if a<b else (b,a))
        for a,b in keys:
            pool=sorted(set(singles.get(a,())+singles.get(b,())+doubles.get((a,b),())))
            if len(pool)<2:continue
            for i,x in enumerate(pool):
                for y in pool[i+1:]:
                    two_moves+=1
                    if conflict(x,y,digits):continue
                    nb=(bits^(1<<a)^(1<<b))|(1<<x)|(1<<y)
                    if nb.bit_count()!=N:raise RuntimeError('two-swap cardinality drift')
                    if nb in seen:continue
                    if len(seen)>=args.cap:truncated=True;continue
                    seen.add(nb);parent[nb]=(bits,'two',(a,b,x,y));q.append(nb);two_new+=1
        if processed%100==0:print('PROGRESS',json.dumps({'processed':processed,'seen':len(seen),'queue':len(q),'two_moves':two_moves,'two_new':two_new,'best_bad':best_bad,'truncated':truncated},sort_keys=True),flush=True)
        if truncated and len(seen)>=args.cap:break
    status={'method':'bpz-t9-X-closure-under-1-and-2-swaps','candidate':winner is not None,'cap':args.cap,'truncated':truncated,'initial_X_private_component':len(Xcomp),'states_seen':len(seen),'states_processed':processed,'queue_remaining':len(q),'one_swap_new_states':one_new,'two_swap_pairs_tested':two_moves,'two_swap_new_states':two_new,'zero_conflict_states':zero_states,'max_private_owner_count':max_single_owners,'max_double_support_groups':max_double_groups,'best_double_hits':best_bad,**ost}
    args.status.parent.mkdir(parents=True,exist_ok=True)
    if winner is None:
        status['closure_complete']=not truncated and not q;status['score']=134753;args.status.write_text(json.dumps(status,indent=2,sort_keys=True)+'\n');print('NONE',json.dumps(status,sort_keys=True),flush=True);return
    Xbits,w=winner;Ibits,pairs,o,PH,PV=w;pts,xp=build(Ibits,Xbits,pairs,PH,PV,ring);status.update({'score':len(pts),'winning_private_pairs':[list(z) for z in pairs],'winning_orientation':list(o),'PH':PH,'PV':PV,'X_partition':{'X0':xp[0],'XH':xp[1],'XV':xp[2]}});args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps({'points':pts},separators=(',',':'))+'\n');args.status.write_text(json.dumps(status,indent=2,sort_keys=True)+'\n');print('FOUND',json.dumps(status,sort_keys=True),flush=True)
if __name__=='__main__':main()
