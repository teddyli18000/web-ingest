#!/usr/bin/env python3
"""Exact independence numbers of the 50 nonconfusable zero-stabilizer orbits.

Fix 00000 in C7^5.  The stabilizer generated by coordinate permutations and
independent sign reversals partitions every vertex nonconfusable with zero into
50 orbit types, represented by sorted cyclic-distance multisets in {0,1,2,3}^5.

For each orbit this script builds its induced C7^5 conflict graph and computes
alpha exactly with RC2 weighted MaxSAT.  Orbits are independent jobs and are
processed in parallel worker processes.  The result is intended to strengthen
the exact pigeonhole symmetry decomposition for a hypothetical 368-set; it is
not itself a global bound on alpha(C7^5).
"""
from __future__ import annotations

import argparse
import itertools
import json
import multiprocessing as mp
from pathlib import Path

from pysat.examples.rc2 import RC2
from pysat.formula import WCNF

Q=7
D=5
POW=tuple(Q**i for i in range(D))


def enc(a):
    return sum(int(a[i])*POW[i] for i in range(D))


def dec(v):
    return tuple((v//POW[i])%Q for i in range(D))


def orbit_types():
    out=[t for t in itertools.combinations_with_replacement(range(4),D) if max(t)>=2]
    if len(out)!=50:
        raise RuntimeError(('orbit count',len(out)))
    return out


def orbit_points(t):
    pts=set()
    for p in set(itertools.permutations(t)):
        nz=[i for i,x in enumerate(p) if x]
        for signs in itertools.product((1,-1),repeat=len(nz)):
            a=list(p)
            for i,s in zip(nz,signs):
                a[i]=(s*a[i])%Q
            pts.add(enc(a))
    return tuple(sorted(pts))


def neighbors(v):
    a=dec(v)
    for d in itertools.product((-1,0,1),repeat=D):
        if all(x==0 for x in d):
            continue
        yield enc(tuple((a[i]+d[i])%Q for i in range(D)))


def independent(S):
    S=set(S)
    for v in S:
        for u in neighbors(v):
            if u in S:
                return False
    return True


def solve_one(arg):
    idx,t=arg
    pts=orbit_points(t)
    pos={v:i+1 for i,v in enumerate(pts)}
    pset=set(pts)
    edges=[]
    for v in pts:
        iv=pos[v]
        for u in neighbors(v):
            if u in pset and u>v:
                edges.append((iv,pos[u]))
    w=WCNF()
    for a,b in edges:
        w.append([-a,-b])
    for i in range(1,len(pts)+1):
        w.append([i],weight=1)
    with RC2(w,solver='g4',adapt=True,exhaust=True,verbose=0) as rc2:
        model=rc2.compute()
        cost=int(rc2.cost)
    if model is None:
        raise RuntimeError(('no model',idx,t))
    poslit={z for z in model if z>0}
    chosen=tuple(pts[i-1] for i in range(1,len(pts)+1) if i in poslit)
    alpha=len(pts)-cost
    if len(chosen)!=alpha or not independent(chosen):
        raise RuntimeError(('replay',idx,t,len(chosen),alpha))
    return {
        'orbit_index':idx,
        'type':list(t),
        'orbit_size':len(pts),
        'conflict_edges':len(edges),
        'alpha':alpha,
        'witness':list(chosen),
    }


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('output',type=Path)
    ap.add_argument('--workers',type=int,default=max(1,mp.cpu_count()))
    a=ap.parse_args()
    types=orbit_types()
    workers=max(1,min(a.workers,len(types)))
    with mp.get_context('fork').Pool(workers) as pool:
        rows=[]
        for row in pool.imap_unordered(solve_one,list(enumerate(types)),chunksize=1):
            rows.append(row)
            print('ORBIT',json.dumps({k:v for k,v in row.items() if k!='witness'},sort_keys=True),flush=True)
    rows.sort(key=lambda r:r['orbit_index'])
    if [tuple(r['type']) for r in rows]!=types:
        raise RuntimeError('type order/replay')
    # The 50 orbits must partition exactly the 16807-3^5 vertices that are
    # nonconfusable with zero.
    if sum(r['orbit_size'] for r in rows)!=7**5-3**5:
        raise RuntimeError(('orbit partition',sum(r['orbit_size'] for r in rows)))
    hist={}
    for r in rows:
        hist[str(r['alpha'])]=hist.get(str(r['alpha']),0)+1
    out={
        'method':'exact-c7p5-zero-stabilizer-orbit-alpha-rc2',
        'orbit_count':50,
        'partition_vertices':sum(r['orbit_size'] for r in rows),
        'alpha_histogram':hist,
        'alpha_lt8':[r['orbit_index'] for r in rows if r['alpha']<8],
        'rows':rows,
    }
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(json.dumps(out,indent=2,sort_keys=True)+'\n')
    print('SUMMARY',json.dumps({k:v for k,v in out.items() if k!='rows'},sort_keys=True),flush=True)

if __name__=='__main__':
    main()
